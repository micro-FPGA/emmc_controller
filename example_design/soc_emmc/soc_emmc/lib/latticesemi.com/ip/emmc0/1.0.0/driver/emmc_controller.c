/**
 * @brief   Function to set the eMMC clock frequency
 *
 * This API is used to set the eMMC clock frequency.
 *
 * @param   handle           Handle of the emmc_ctl_handle_t structure
 * @param   sck_freq         Clock frequency (in KHz) to be set
 * @return                   Returns 'SUCCESS' (0) on success,
 *                   or 'FAILURE' (1) if input pointer is NULL.
 */

unsigned char set_emmc_clock_freq_khz(emmc_ctl_handle_t *handle,
                unsigned int sck_freq)
{
  unsigned char status = FAILURE;
  unsigned int rdat;
  unsigned int sck_rate;
  unsigned int new_rate;

  if (!handle)
    return FAILURE;

  if(handle->base_addr == ZERO)
    return FAILURE;

  emmc_ctl_reg_t *emmc_ctl=(emmc_ctl_reg_t *)(handle->base_addr);

  rdat     = emmc_ctl->EMMC_REG_CONFIG0;
  sck_rate = GET_FIELD_VAL(rdat,EMMC_CFG0_SCK_RATE_IDX,16);
  new_rate = ((handle->sys_clk_freq_khz + (2 * sck_freq) - 1) / (2 * sck_freq));

  if(sck_freq >= handle->sys_clk_freq_khz)
    new_rate  = 0;

  if(new_rate != sck_rate) {
    /* In case there is ongoing eMMC transaction, wait until it is done */
    wait_emmc_ctl_busy_status(handle,0);
    /* Reprogram new rate */
    SET_REG_FIELD(rdat, new_rate, 16, EMMC_CFG0_SCK_RATE_IDX);
    emmc_ctl->EMMC_REG_CONFIG0  = rdat;
  }

  handle->sck_rate = new_rate;
  handle->emmc_sck_freq_khz = (unsigned int)((new_rate == 0)? handle->sys_clk_freq_khz :
                                                              (handle->sys_clk_freq_khz/new_rate/2));

  status = SUCCESS;
  return status;
}

