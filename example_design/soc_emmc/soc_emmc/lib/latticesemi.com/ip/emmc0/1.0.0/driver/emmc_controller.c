/**
 * @brief   Private/Internal function to poll the eMMC status by reading the eMMC
 *          information status register
 *
 * This API is used to poll the eMMC Controller status by reading the
 * information status register (offset 0x100).
 *
 * @param   handle           Handle of the emmc_ctl_handle_t structure
 * @param   wait_value       Expected value for eMMC busy status done
 * @return                   Returns 'SUCCESS' (0) on success,
 *                   or 'FAILURE' (1) if input pointer is NULL.
 */
unsigned char wait_emmc_ctl_busy_status(emmc_ctl_handle_t *handle,
                  unsigned int wait_value)
{
  unsigned char status = FAILURE;
  unsigned int emmc_busy;
  unsigned int wait_done;
  volatile unsigned int rdat;

  if (!handle)
    return FAILURE;

  if(handle->base_addr == ZERO)
    return FAILURE;

  emmc_ctl_reg_t *emmc_ctl  = (emmc_ctl_reg_t *)(handle->base_addr);
  wait_done                 = 0;
  emmc_busy                 = 0;

  do
  {
    rdat = emmc_ctl->EMMC_REG_INFO_STATUS;
    emmc_busy = rdat & EMMC_INFO_STS_BUSY;

    if(emmc_busy == wait_value)
      wait_done = 1;
  }
  while(!wait_done);

  status = SUCCESS;
  return status;
}


