unsigned char emmc_cmd_send_op_cond(emmc_ctl_handle_t *handle)
{
  unsigned char status = FAILURE;
  unsigned int  rdat;
  unsigned int  cmd_arg;
  unsigned char cmd_done;
  unsigned char det_err;

  if (!handle)
    return FAILURE;

  if(handle->base_addr == ZERO)
    return FAILURE;

  emmc_ctl_reg_t *emmc_ctl=(emmc_ctl_reg_t *)(handle->base_addr);

  emmc_ctl->EMMC_REG_CONFIG1 = 0;

  // OCR[31]    = 0x0   -> card power up status
  // OCR[30:29] = 0x2   -> sector mode
  // OCR[28:24] = 0x00  -> reserved
  // OCR[23:15] = 0x1FF -> 2.7-3.6V
  // OCR[14:8]  = 0x00  -> 2.0-2.6V
  // OCR[7]     = 0x1   -> 1.7-1.95V
  // OCR[6:0]   = 0x00  -> reserved
  cmd_arg = 0x40FF8080;

  emmc_ctl->EMMC_REG_CTRL0 = 0;
  emmc_ctl->EMMC_REG_CTRL1 = cmd_arg;


  cmd_done  = 0;
  det_err   = 0;
  do
  {
    emmc_ctl->EMMC_REG_CTRL2 = (EMMC_CTRL2_START | EMMC_CMD_SEND_OP_COND);
    wait_emmc_ctl_busy_status(handle,0);
    rdat = emmc_ctl->EMMC_REG_RESP_D1;

    // read interrupt status, check that it is not due to timeout
    rdat                          = emmc_ctl->EMMC_REG_INT_STATUS;
    cmd_done                      = (GET_FIELD_VAL(rdat,EMMC_INT_CMD_TIMEOUT_IDX,2) == ZERO)? 1 : 0;
    det_err                       = ((rdat & 0xFFFFFFFE) == ZERO)? 0 : 1;

    // check if device is ready (from OCR[31])
    if(cmd_done)
    {
      rdat                        = emmc_ctl->EMMC_REG_RESP_D1;
      cmd_done                    = ((rdat & 0x80000000) == ZERO)? 0 : 1;
    }

    // clear interrupt status
    emmc_ctl->EMMC_REG_INT_STATUS = SET_ALL_BITS;
  }
  while(!cmd_done);

  emmc_get_resp_data(handle);

  status = (det_err == ZERO)? SUCCESS : FAILURE;
  return status;
}

