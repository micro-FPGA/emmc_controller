/**
 * @brief   Function to initializes the eMMC Controller IP.
 *
 * This API initializes the eMMC Controller IP with the following actions:
 * - Assigns the base address to the emmc_ctl_reg_t struct.
 * - Initializes the eMMC configuration derived from the input pointer
 *   (refer to the emmc_ctl_handle_t struct).
 * - Enables the interrupt.
 *
 * @param   handle        Pointer of Handle of the emmc_ctl_handle_t structure.
 * @param   base_addr       Base address to be assigned.
 * @return                      Returns 'SUCCESS' (0) on success,
 *                  or 'FAILURE' (1) if input pointer is NULL.
 */

unsigned char emmc_ctl_init( emmc_ctl_handle_t *handle)
{
  unsigned char status = FAILURE;
  unsigned int rdat;

  if (!handle)
    return FAILURE;

  if(handle->base_addr == ZERO)
    return FAILURE;

  emmc_ctl_reg_t *emmc_ctl = (emmc_ctl_reg_t *)(handle->base_addr);

  // Assert IP core reset and target reset
  emmc_ctl->EMMC_REG_SOFT_RESET = 0x3;

  /* Update Configuration 0 register */
  rdat = emmc_ctl->EMMC_REG_CONFIG0;

  SET_REG_FIELD(rdat, handle->sck_rate, 16, EMMC_CFG0_SCK_RATE_IDX);

  emmc_ctl->EMMC_REG_CONFIG0 = rdat;
  emmc_ctl->EMMC_REG_CONFIG1 = 0;

  emmc_ctl->EMMC_REG_INT_ENABLE = handle->interrupt_enable;

  handle->emmc_block_size = 512; // default block size
  handle->tgt_addr        = 0;   // to be assigned later

  // De-assert IP core reset and target reset
  emmc_ctl->EMMC_REG_SOFT_RESET = 0;

  status = SUCCESS;

  return status;
}

