unsigned char get_block_size_encoding(unsigned int blocklen)
{
  unsigned char block_size;

  switch (blocklen)
  {
    case 16    : block_size = BLKLEN_16B ; break;
    case 32    : block_size = BLKLEN_32B ; break;
    case 64    : block_size = BLKLEN_64B ; break;
    case 128   : block_size = BLKLEN_128B; break;
    case 256   : block_size = BLKLEN_256B; break;
    case 512   : block_size = BLKLEN_512B; break;
    case 1024  : block_size = BLKLEN_1KB ; break;
    case 2048  : block_size = BLKLEN_2KB ; break;
    case 4096  : block_size = BLKLEN_4KB ; break;
    case 8192  : block_size = BLKLEN_8KB ; break;
    case 16384 : block_size = BLKLEN_16KB; break;
    case 32768 : block_size = BLKLEN_32KB; break;
    default    : block_size = BLKLEN_512B; break;
  }

  return block_size;
}

